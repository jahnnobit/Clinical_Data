"""
build_edit_check_spec.py
------------------------
Creates docs/Edit_Check_Specification.xlsx: one row per edit check.

An *edit check* is a pre-defined rule that tests clinical data for missing,
invalid or inconsistent values. Each failing record becomes a *query* to the
site. The *edit check specification* is the document where data management
defines these rules before programming them, so they can be reviewed and
approved (and later traced back during an audit).

The spec is generated by this script (instead of typed by hand in Excel) so it
is reproducible and version-controlled together with the code.

Run from the project root:
    python data_quality_review/src/build_edit_check_spec.py
"""

