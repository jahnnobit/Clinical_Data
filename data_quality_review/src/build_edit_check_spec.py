COLUMNS = ["Check ID", "Dataset", "Variable(s)", "Rule", "Logic", "Severity", "Query text", "Notes"]
COLUMN_WIDTHS = [10, 10, 26, 45, 55, 10, 55, 60]

SEVERITY_DEFINITIONS = [
    ("Critical", "Affects subject identity or patient safety data. Must be resolved before database lock."),
    ("Major", "Affects data used in analysis (wrong, missing or inconsistent value). Must be resolved or documented before lock."),
    ("Minor", "Completeness or review item with little impact on analysis. May be accepted with documentation."),
]


def write_spec(path=OUTPUT_FILE):
    wb = Workbook()

    # ---- Sheet 1: the checks ----
    ws = wb.active
    ws.title = "Edit Checks"
    ws.append(COLUMNS)
    for check in CHECKS:
        ws.append([check[c] for c in COLUMNS])

    header_fill = PatternFill("solid", fgColor="1F4E78")
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        cell.alignment = Alignment(vertical="center", wrap_text=True)
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
    for i, width in enumerate(COLUMN_WIDTHS, start=1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = width
    ws.freeze_panes = "B2"                 # keep header row and Check ID visible
    ws.auto_filter.ref = ws.dimensions     # filter buttons on the header

    # ---- Sheet 2: document information ----
    info = wb.create_sheet("About")
    rows = [
        ("Document", "Edit Check Specification"),
        ("Project", "Clinical Trial Data Quality Review (portfolio project)"),
        ("Data", "CDISC pilot SDTM test data (DM, AE, VS, LB) from the pharmaversesdtm package: "
                 "https://github.com/pharmaverse/pharmaversesdtm"),
        ("Status", "Portfolio project on public data. Not real clinical trial work."),
        ("Number of checks", len(CHECKS)),
        ("", ""),
        ("Conventions", ""),
        ("Missing value", "An empty cell (NA in the source CSV)."),
        ("Dates", "ISO 8601. Partial dates (YYYY, YYYY-MM) are allowed. " + SHARED_PRECISION),
        ("Plausibility limits", "Numeric limits in DM02, VS01 and VS03 are assumed plausibility limits, not clinical rules."),
        ("Query text", "Neutral and specific. Never suggests the 'correct' value."),
        ("", ""),
        ("Severity", "Definition"),
    ] + SEVERITY_DEFINITIONS
    for r in rows:
        info.append(list(r))
    for cell in info["A"]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(vertical="top")
    for cell in info["B"]:
        cell.alignment = Alignment(vertical="top", wrap_text=True)
    info.column_dimensions["A"].width = 20
    info.column_dimensions["B"].width = 100

    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    print(f"Wrote {len(CHECKS)} checks to {path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    write_spec()
